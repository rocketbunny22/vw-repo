export function translateMexicanSpanish(value: string): string {
  const direct = mexicanSpanishTranslations[value];
  if (direct) return direct;

  const patterns: Array<[RegExp, string]> = [
    [/^Uploaded by (.+)$/i, 'Subido por $1'],
    [/^By (.+)$/i, 'Por $1'],
    [/^Member since (.+)$/i, 'Miembro desde $1'],
    [/^Reported (.+)$/i, 'Reportado $1'],
    [/^(\d+) PDFs found$/i, '$1 PDFs encontrados'],
    [/^(\d+) guides found$/i, '$1 guías encontradas'],
    [/^(\d+) results for “(.+)”$/i, '$1 resultados para “$2”'],
    [/^Moderation \((\d+)\)$/i, 'Moderación ($1)'],
    [/^Users \((\d+)\)$/i, 'Usuarios ($1)'],
    [/^Guides \((\d+)\)$/i, 'Guías ($1)'],
    [/^From (.+)$/i, 'De $1'],
    [/^Guide: (.+)$/i, 'Guía: $1'],
  ];

  for (const [pattern, replacement] of patterns) {
    if (pattern.test(value)) return value.replace(pattern, replacement);
  }

  return value;
}
